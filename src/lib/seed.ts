/** 実物の本(ユーザー追加)用の伴走セッションを生成する */
export function buildCompanionUnits(bookId: string): Omit<Unit, "readAt">[] {
  const units: Omit<Unit, "readAt">[] = [
    {
      id: `${bookId}-u0`,
      bookId,
      order: 0,
      chapter: 0,
      chapterTitle: "プロローグ",
      title: "読む前の30秒——この本に何を期待する?",
      isPrologue: true,
      paragraphs: [
        "本を読み始める前に、30秒だけ立ち止まる。「この本から、何を一つ持ち帰りたいか」。目的を持って読む人と、なんとなく読む人では、同じ本から得るものがまるで違う。",
        "この本は12回の小さなセッションで読み切る設計だ。1回のセッションは「1見出しぶん(約5分)だけ読む」。それ以上読んでもいいが、義務は1見出しだけ。",
        "準備はこれで完了。次のセッションから、実際に本を開こう。",
      ],
    },
  ];
  const phases = [
    "序盤 まず開く",
    "中盤 芯をつかむ",
    "終盤 読み切る",
  ];
  for (let i = 1; i <= 12; i++) {
    const chapter = i <= 4 ? 1 : i <= 8 ? 2 : 3;
    units.push({
      id: `${bookId}-u${i}`,
      bookId,
      order: i,
      chapter,
      chapterTitle: `${["", "第1部", "第2部", "第3部"][chapter]} ${phases[chapter - 1]}`,
      title: `セッション${i}——続きから1見出しだけ読む`,
      paragraphs: [
        "手元の本を開いて、栞のところから「1見出しぶん」だけ読もう。目安は5分。それ以上読みたくなったら読んでもいいが、ノルマはあくまで1見出しだ。",
        "読み終えたらここに戻って「読んだ」を押し、印象に残った一つを「明日どう使うか」の形で1行だけ書く。完璧な要約は要らない。自分の言葉なら、稚拙でいい。",
        "12セッションで1冊を読み切る計算だ。今日の1見出しが、その1回分になる。",
      ],
    });
  }
  return units;
}

export function createSeedState(): AppState {
  const now = new Date().toISOString();
  const books: Book[] = SEED_BOOKS.map((b, i) => ({
    id: b.id,
    title: b.title,
    author: b.author,
    status: i === 0 ? "reading" : "inbox",
    coverColor: b.coverColor,
    addedAt: now,
    startedAt: i === 0 ? now : undefined,
  }));
  const units: Unit[] = SEED_BOOKS.flatMap((b) =>
    b.units.map((u, i) => ({
      id: `${b.id}-u${i}`,
      bookId: b.id,
      order: i,
      chapter: u.chapter,
      chapterTitle: u.chapterTitle,
      title: u.title,
      paragraphs: u.paragraphs,
      isPrologue: u.isPrologue,
    }))
  );
  return {
    books,
    units,
    cards: [],
    sessions: [],
    settings: {
      anchorHabit: "commute",
      ifThenSentence: "電車に座ったら、ツヅキを開く",
      weeklyGoal: 3,
      onboarded: false,
    },
  };
}
